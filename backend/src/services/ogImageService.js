class CanvasImage {
  constructor(w, h) {
    this.w = w;
    this.h = h;
    this.data = new Uint8Array(w * h * 4).fill(255);
  }

  setPixel(x, y, r, g, b, a = 255) {
    if (x < 0 || x >= this.w || y < 0 || y >= this.h) return;
    const i = (y * this.w + x) * 4;
    this.data[i] = r;
    this.data[i + 1] = g;
    this.data[i + 2] = b;
    this.data[i + 3] = a;
  }

  fillRect(x, y, w, h, r, g, b, a = 255) {
    for (let dy = 0; dy < h; dy++) {
      for (let dx = 0; dx < w; dx++) {
        this.setPixel(x + dx, y + dy, r, g, b, a);
      }
    }
  }

  drawGradientV(x, y, w, h, r1, g1, b1, r2, g2, b2) {
    for (let dy = 0; dy < h; dy++) {
      const t = dy / (h - 1);
      const r = Math.round(r1 + (r2 - r1) * t);
      const g = Math.round(g1 + (g2 - g1) * t);
      const b = Math.round(b1 + (b2 - b1) * t);
      for (let dx = 0; dx < w; dx++) {
        this.setPixel(x + dx, y + dy, r, g, b);
      }
    }
  }

  fillRoundedRect(x, y, w, h, radius, r, g, b, a = 255) {
    for (let dy = 0; dy < h; dy++) {
      for (let dx = 0; dx < w; dx++) {
        const px = x + dx,
          py = y + dy;
        const cx = dx < radius ? radius : dx >= w - radius ? w - radius - 1 : dx;
        const cy = dy < radius ? radius : dy >= h - radius ? h - radius - 1 : dy;
        const dist = Math.sqrt((dx - cx) ** 2 + (dy - cy) ** 2);
        if (dist <= radius) this.setPixel(px, py, r, g, b, a);
      }
    }
  }

  drawText(text, x, y, scale, r, g, b) {
    let cx = x;
    for (const ch of text) {
      const glyph = FONT[ch] || FONT[' '];
      for (let row = 0; row < 8; row++) {
        for (let col = 0; col < 8; col++) {
          if (glyph[row] & (0x80 >> col)) {
            this.fillRect(cx + col * scale, y + row * scale, scale, scale, r, g, b);
          }
        }
      }
      cx += 8 * scale + scale;
    }
  }

  toPngBuffer() {
    const IHDR = buildChunk(
      'IHDR',
      Buffer.concat([u32(this.w), u32(this.h), Buffer.from([8, 2, 0, 0, 0])])
    );
    const rawRows = [];
    for (let y = 0; y < this.h; y++) {
      rawRows.push(0);
      for (let x = 0; x < this.w; x++) {
        const i = (y * this.w + x) * 4;
        rawRows.push(this.data[i], this.data[i + 1], this.data[i + 2]);
      }
    }
    const compressed = zlib.deflateSync(Buffer.from(rawRows));
    const IDAT = buildChunk('IDAT', compressed);
    const IEND = buildChunk('IEND', Buffer.alloc(0));
    return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), IHDR, IDAT, IEND]);
  }
}

function u32(n) {
  const b = Buffer.allocUnsafe(4);
  b.writeUInt32BE(n, 0);
  return b;
}

function buildChunk(type, data) {
  const typeBytes = Buffer.from(type, 'ascii');
  const crc = zlib.crc32(Buffer.concat([typeBytes, data]));
  return Buffer.concat([u32(data.length), typeBytes, data, u32(crc)]);
}

function wrapText(text, maxChars) {
  const words = String(text || '').split(' ');
  const lines = [];
  let line = '';
  for (const word of words) {
    if ((line + ' ' + word).trim().length > maxChars) {
      if (line) lines.push(line.trim());
      line = word;
    } else {
      line = (line + ' ' + word).trim();
    }
    if (lines.length >= 2) break;
  }
  if (line && lines.length < 2) lines.push(line.trim());
  return lines;
}

async function generateCampaignOgImage({
  title,
  creatorName,
  raisedAmount,
  targetAmount,
  assetType,
  campaignUrl,
}) {
  const img = new CanvasImage(W, H);

  img.drawGradientV(0, 0, W, H, 15, 23, 42, 30, 41, 77);

  const pct = targetAmount > 0 ? Math.min(1, Number(raisedAmount) / Number(targetAmount)) : 0;
  const barX = 48,
    barY = 290,
    barW = W - 96,
    barH = 14;
  img.fillRoundedRect(barX, barY, barW, barH, 7, 45, 55, 80);
  const fill = Math.round(barW * pct);
  if (fill > 0) img.fillRoundedRect(barX, barY, fill, barH, 7, 99, 179, 237);

  const raised = Number(raisedAmount || 0).toFixed(2);
  const target = Number(targetAmount || 0).toFixed(2);
  const asset = String(assetType || 'USDC');
  const progressLabel = `${raised} / ${target} ${asset}`;

  const titleLines = wrapText(title || 'Campaign', 42);
  titleLines.forEach((line, i) => img.drawText(line, 48, 60 + i * 36, 3, 240, 240, 255));

  const byLine = `by ${(creatorName || 'Creator').slice(0, 32)}`;
  img.drawText(byLine, 48, 180, 2, 160, 170, 200);

  img.drawText(progressLabel, 48, 224, 2, 200, 210, 240);

  img.fillRoundedRect(48, 320, 200, 42, 10, 99, 179, 237);
  img.drawText('Get funded', 66, 334, 2, 255, 255, 255);

  if (campaignUrl) {
    try {
      const qr = QRCode.create(campaignUrl, { errorCorrectionLevel: 'M' });
      const size = qr.modules.size;
      const qrX = W - 160,
        qrY = H - 160,
        cellSize = Math.floor(140 / size);
      img.fillRect(qrX - 5, qrY - 5, size * cellSize + 10, size * cellSize + 10, 255, 255, 255);
      for (let r = 0; r < size; r++) {
        for (let c = 0; c < size; c++) {
          if (qr.modules.get(r, c)) {
            img.fillRect(qrX + c * cellSize, qrY + r * cellSize, cellSize, cellSize, 15, 23, 42);
          }
        }
      }
    } catch {
      // ignore QR generation errors and proceed without QR
    }
  }

  return img.toPngBuffer();
}

